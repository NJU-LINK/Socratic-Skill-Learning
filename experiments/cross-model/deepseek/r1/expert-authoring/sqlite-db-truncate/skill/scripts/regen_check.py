#!/usr/bin/env python3
"""Byte-level verification of a row-recovery hypothesis for a damaged DB.

Usage:
  regen_check.py ORIGINAL_DB ROWS_JSON --create "CREATE TABLE ..." --table NAME

ROWS_JSON accepts any of:
  * a list of row lists (values in column order, insertion order),
  * a bare list of objects (keys used in first-object order),
  * a {"table": [objects], ...} object exactly as emitted by
    `sqlite_raw.py dump`.

The tool rebuilds a fresh database with sqlite3 from the hypothesis rows, then
byte-diffs it against the damaged file and classifies every differing byte.

Classification
--------------
  explained:
    * writer-version stamp bytes (file offsets 96..99): differ whenever the
      regenerating sqlite build is not the one that wrote the original.
    * single-bit differences (popcount(a ^ b) == 1): one bit flip -- exactly
      the damage signature of this task family (structural flips plus
      zero->single-bit noise).  A hypothesis whose regen matches the damaged
      file everywhere except 1-bit flips and the version stamp is proven
      byte-exact modulo the corruption.
  unexplained:
    * multi-bit differences outside the version stamp (zeroed regions,
      truncation/padding, or a wrong hypothesis: wrong value, wrong type,
      wrong row order, missing/extra rows).
    * size mismatches.

Exit code: 0 = all diffs explained, 1 = unexplained diffs remain.
"""
import json
import os
import sqlite3
import sys
import tempfile

STAMP_LO, STAMP_HI = 96, 100          # writer-version stamp region
SINGLE_BIT = {1, 2, 4, 8, 16, 32, 64, 128}


def popcount(x):
    return bin(x).count("1")


def build_fresh_db(rows, create, table):
    """Rebuild a hypothesis DB; returns bytes of the regenerated file."""
    fd, tmp = tempfile.mkstemp(suffix=".db")
    os.close(fd)
    try:
        con = sqlite3.connect(tmp)
        con.execute(create)
        if rows:
            cols = ",".join("?" * len(rows[0]))
            con.executemany(f"INSERT INTO {table} VALUES ({cols})", rows)
        con.commit()
        con.close()
        return open(tmp, "rb").read()
    finally:
        try:
            os.unlink(tmp)
        except Exception:
            pass


def classify_and_report(orig_path, orig, regen, nrows):
    """Diff damaged vs regenerated bytes; print classified report.
    Returns 0 when every diff is explained (stamp or 1-bit flip),
    1 when unexplained multi-bit diffs or a size mismatch remain."""
    if len(orig) != len(regen):
        print(f"UNEXPLAINED: size mismatch "
              f"(damaged={len(orig)} regen={len(regen)}) "
              f"- truncation/padding or missing/extra rows")
        print("VERDICT: hypothesis NOT proven")
        return 1
    explained = unexplained = noise = flips = stamp = 0
    unexplained_list = []
    for off, (a, b) in enumerate(zip(orig, regen)):
        if a == b:
            continue
        if STAMP_LO <= off < STAMP_HI:
            stamp += 1
            explained += 1
            continue
        if popcount(a ^ b) == 1:
            flips += 1
            explained += 1
            if b == 0 and a in SINGLE_BIT:
                noise += 1
            continue
        unexplained += 1
        unexplained_list.append((off, a, b))
    print(f"damaged: {os.path.basename(orig_path)} ({len(orig)} bytes)")
    print(f"hypothesis rows: {nrows}")
    print(f"differing bytes: {explained + unexplained}")
    print(f"  writer-version stamp bytes: {stamp} (expected across builds)")
    print(f"  single-bit flips: {flips} (of which {noise} are "
          f"zero->single-bit noise)")
    print(f"  unexplained multi-bit diffs: {unexplained}")
    for off, a, b in unexplained_list[:40]:
        print(f"    UNEXPLAINED 0x{off:05x}: damaged=0x{a:02x} "
              f"regen=0x{b:02x}")
    if len(unexplained_list) > 40:
        print(f"    ... {len(unexplained_list) - 40} more")
    if unexplained:
        print("VERDICT: hypothesis NOT proven - investigate the listed "
              "offsets (wrong value/type/order, missing rows, or "
              "zeroed/truncated damage)")
        return 1
    print("VERDICT: hypothesis proven byte-exact modulo single-bit flips "
          "and the version stamp")
    return 0


def run(orig_path, rows, create, table):
    """Rebuild, classify, report; returns exit code."""
    orig = open(orig_path, "rb").read()
    regen = build_fresh_db(rows, create, table)
    return classify_and_report(orig_path, orig, regen, len(rows))


def main():
    args = sys.argv[1:]
    if len(args) < 2 or args[0] in ("-h", "--help", "help"):
        print(__doc__)
        sys.exit(0 if args and args[0] in ("-h", "--help", "help") else 2)
    orig_path, rows_path = args[0], args[1]
    create = None
    table = None
    i = 2
    while i < len(args):
        if args[i] == "--create":
            create = args[i + 1]; i += 2
        elif args[i] == "--table":
            table = args[i + 1]; i += 2
        else:
            i += 1
    if create is None or table is None:
        print(__doc__)
        sys.exit(2)
    try:
        rows = json.load(open(rows_path))
    except Exception as e:
        print(f"cannot load hypothesis JSON: {e}", file=sys.stderr)
        sys.exit(2)
    # accept three shapes: list of lists (canonical), bare list of dicts,
    # or {"table": [dicts]} as emitted by `sqlite_raw.py dump`
    if isinstance(rows, dict) and rows:
        rows = next(iter(rows.values()))
    if rows and isinstance(rows[0], dict):
        keys = list(rows[0].keys())
        rows = [[r.get(k) for k in keys] for r in rows]
    if not isinstance(rows, list) or not all(
            isinstance(r, list) for r in rows):
        print("hypothesis JSON must be rows as lists or objects",
              file=sys.stderr)
        sys.exit(2)
    # blobs decoded as int-lists must be re-encoded as bytes for sqlite
    rows = [[bytes(v) if isinstance(v, list) and v else v for v in r]
            for r in rows]
    sys.exit(run(orig_path, rows, create, table))


if __name__ == "__main__":
    main()